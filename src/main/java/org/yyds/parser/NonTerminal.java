package org.yyds.parser;

/**
 * 语法分析中使用的非终结符
 */
public enum NonTerminal {
    /**
     * 程序的起始符号，表示整个源代码文件。
     */
    PROGRAM,
    /**
     * 声明列表，可以包含多个类声明、函数声明或变量声明。
     */
    DECL_LIST,
    /**
     * 声明，可以是类声明、函数声明或变量声明，具体由 {@code DECL_TAIL} 区分。
     */
    DECL,
    /**
     * 声明的尾部，根据前面是否是类型来区分函数声明和变量声明。
     */
    DECL_TAIL,
    /**
     * 类型，可以是内置类型（int、bool、void）或用户定义的类名。
     */
    TYPE,
    /**
     * 变量声明的尾部，根据是否有初始化表达式来区分不同的变量声明形式。
     */
    VAR_DECL_TAIL,
    /**
     * 参数列表的可选部分，根据是否有参数来区分函数声明中参数列表的不同形式。
     */
    PARAM_LIST_OPT,
    /**
     * 参数列表，可以包含一个或多个参数，每个参数由类型和标识符组成，参数之间用逗号分隔。
     */
    PARAM_LIST,
    /**
     * 参数列表的尾部，根据是否有逗号来区分参数列表中参数之间的不同形式。
     */
    PARAM_LIST_TAIL,
    /**
     * 参数，由类型和标识符组成，表示函数声明中一个参数的定义。
     */
    PARAM,
    /**
     * 成员列表，可以包含多个成员，每个成员可以是访问说明符、函数声明或变量声明，
     * 具体由 {@code ACCESS_SPEC_OPT} 和 {@code MEMBER} 区分。
     */
    MEMBER_LIST,
    /**
     * 访问说明符的可选部分，根据是否有访问说明符来区分类成员列表中不同成员的访问权限。
     */
    ACCESS_SPEC_OPT,
    /**
     * 成员，可以是函数成员或变量成员，根据前面是否有访问说明符来区分类成员列表中不同成员的定义形式。
     */
    MEMBER,
    /**
     * 语句块，由一对大括号包围，内部可以包含零个或多个语句，表示函数体或控制结构中的代码块。
     */
    BLOCK,
    /**
     * 语句列表，可以包含零个或多个语句，表示一个代码块中的所有语句。
     */
    STMT_LIST,
    /**
     * 语句，可以是变量声明、表达式语句、条件语句、循环语句、返回语句或代码块，
     * 具体由后续的非终结符区分不同类型的语句。
     */
    STMT,
    /**
     * 标识符语句的尾部，根据是否有赋值操作来区分标识符语句中不同的表达式形式。
     */
    IDENTIFIER_STMT_TAIL,
    /**
     * 条件语句，由 if 关键字引导，包含一个条件表达式和一个语句块，可以选择性地包含一个 else 部分。
     */
    IF_STMT,
    /**
     * else 部分，根据是否有 else 关键字来区分条件语句中不同的分支结构。
     */
    ELSE_PART,
    /**
     * 循环语句，由 while 关键字引导，包含一个条件表达式和一个语句块，表示循环结构。
     */
    WHILE_STMT,
    /**
     * 返回语句，由 return 关键字引导，可以选择性地包含一个返回表达式，表示函数的返回值。
     */
    RETURN_STMT,
    /**
     * 返回表达式的可选部分，根据是否有返回表达式来区分返回语句中不同的返回形式。
     */
    RETURN_EXPR_OPT,
    /**
     * 表达式，表示各种类型的表达式，包括逻辑表达式、关系表达式、算术表达式等，
     * 具体由后续的非终结符区分不同类型的表达式结构。
     */
    EXPR,
    /**
     * 逻辑或表达式，由一个或多个逻辑与表达式通过 OR 运算符连接而成，表示逻辑或关系。
     */
    LOGIC_OR_EXPR,
    /**
     * 逻辑或表达式的尾部，根据是否有 OR 运算符来区分逻辑或表达式中不同的连接形式。
     */
    LOGIC_OR_EXPR_TAIL,
    /**
     * 逻辑与表达式，由一个或多个关系表达式通过 AND 运算符连接而成，表示逻辑与关系。
     */
    LOGIC_AND_EXPR,
    /**
     * 逻辑与表达式的尾部，根据是否有 AND 运算符来区分逻辑与表达式中不同的连接形式。
     */
    LOGIC_AND_EXPR_TAIL,
    /**
     * 相等表达式，由一个关系表达式和一个相等表达式尾部组成，表示相等关系。
     */
    EQUALITY_EXPR,
    /**
     * 相等表达式的尾部，根据是否有 EQ 或 NEQ 运算符来区分相等表达式中不同的连接形式。
     */
    EQUALITY_EXPR_TAIL,
    /**
     * 关系表达式，由一个加法表达式和一个关系表达式尾部组成，表示关系比较。
     */
    REL_EXPR,
    /**
     * 关系表达式的尾部，根据是否有 LT、GT、LE 或 GE 运算符来区分关系表达式中不同的连接形式。
     */
    REL_EXPR_TAIL,
    /**
     * 加法表达式，由一个乘法表达式和一个加法表达式尾部组成，表示加法运算。
     */
    ADD_EXPR,
    /**
     * 加法表达式的尾部，根据是否有 PLUS 或 MINUS 运算符来区分加法表达式中不同的连接形式。
     */
    ADD_EXPR_TAIL,
    /**
     * 乘法表达式，由一个一元表达式和一个乘法表达式尾部组成，表示乘法运算。
     */
    MUL_EXPR,
    /**
     * 乘法表达式的尾部，根据是否有 STAR、SLASH 或 PERCENT 运算符来区分乘法表达式中不同的连接形式。
     */
    MUL_EXPR_TAIL,
    /**
     * 一元表达式，可以由一个一元运算符（PLUS、MINUS、NOT）和一个一元表达式组成，
     * 也可以是一个基本表达式，表示一元运算或基本表达式。
     */
    UNARY_EXPR,
    /**
     * 基本表达式，可以是一个标识符、一个字面量、一个括号中的表达式或一个函数调用，
     * 具体由后续的非终结符区分不同类型的基本表达式结构。
     */
    PRIMARY
}
